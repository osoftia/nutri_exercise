using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using NutriExercise.Core.Constants;
using NutriExercise.Core.Entities;

namespace NutriExercise.Infrastructure.Data;

/// <summary>
/// EF Core database initializer for the RAG feature.
///
/// Ensures the <c>Users</c> table contains the default test user
/// (<c>Id = 1, Name = 'Test User', Email = 'test@nutriexercise.local'</c>)
/// so document ingestion and RAG queries can associate records with
/// <c>UserId = 1</c> without requiring login. Idempotent and safe to
/// run on every startup (local Mac server included).
/// </summary>
public static class DbInitializer
{
    public static async Task SeedAsync(
        AppDbContext context,
        ILogger logger,
        CancellationToken cancellationToken = default)
    {
        try
        {
            await context.Database.MigrateAsync(cancellationToken);

            var existing = await context.Users.FindAsync(
                new object[] { RagDefaults.DefaultUserId }, cancellationToken);

            if (existing is null)
            {
                // Identity insert: explicit Id = 1 on a GENERATED BY DEFAULT column.
                context.Users.Add(new User
                {
                    Id = RagDefaults.DefaultUserId,
                    Name = RagDefaults.DefaultUserName,
                    Email = RagDefaults.DefaultUserEmail,
                });
                await context.SaveChangesAsync(cancellationToken);
                logger.LogInformation(
                    "[RAG-INFO]: database seeding completed — default test user ensured (UserId = {UserId}, Email = {Email}).",
                    RagDefaults.DefaultUserId, RagDefaults.DefaultUserEmail);
            }
            else
            {
                var normalized = false;
                if (existing.Name != RagDefaults.DefaultUserName)
                {
                    existing.Name = RagDefaults.DefaultUserName;
                    normalized = true;
                }
                if (existing.Email != RagDefaults.DefaultUserEmail)
                {
                    existing.Email = RagDefaults.DefaultUserEmail;
                    normalized = true;
                }
                if (normalized)
                {
                    await context.SaveChangesAsync(cancellationToken);
                }
                logger.LogInformation(
                    "[RAG-INFO]: database seeding skipped — default test user already exists (UserId = {UserId}).",
                    RagDefaults.DefaultUserId);
            }
        }
        catch (Exception ex) when (ex is Npgsql.NpgsqlException or Microsoft.EntityFrameworkCore.DbUpdateException or InvalidOperationException)
        {
            logger.LogError(
                ex,
                "[RAG-ERROR]: database connectivity failure during seeding — could not ensure default test user (UserId = {UserId}).",
                RagDefaults.DefaultUserId);
            throw;
        }
        catch (Exception ex)
        {
            logger.LogError(
                ex,
                "[RAG-ERROR]: internal processing error during database seeding (UserId = {UserId}).",
                RagDefaults.DefaultUserId);
            throw;
        }
    }
}
